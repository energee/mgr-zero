-- 20260913110000_hosted_schema_catchup.sql — brings the hosted database up to
-- the schema the code expects.
--
-- Why this file exists. `scripts/vercel-build.sh` runs `supabase db push`,
-- which applies a migration *version* once and never looks at that file again.
-- Both existing migrations were edited in place after they had been applied:
-- 20260910120847 grew from 108KB to 295KB (#303, #307, #315, #317, #319) and
-- 00001_baseline.sql kept taking edits (#320, #326). Every one of those edits
-- reached CI, which builds a database from scratch, and never reached hosted.
--
-- The result was issue #330 (/settings, /menu and /settings/pos/mapping hit the
-- error boundary) and the live half of #329 (Ask MGR reports "database error"):
-- the code reads staff_brewery.ai_model, private.chat_conversations and the
-- Square catalog tables, none of which exist on hosted.
--
-- This delta was generated by migra between two local databases — one built
-- from the two migrations as hosted applied them (their content at f93121f0,
-- the deploy that first ran them), one built from the files as they stand —
-- then verified by applying it to the first and diffing the result against the
-- second. 112 objects were missing on hosted; nothing existed there that the
-- current schema does not have.
--
-- The one destructive statement is pos_connections.expires_at, which #307/#317
-- replaced with access_expires_at / refresh_expires_at. No hosted data is lost:
-- nothing has shipped to customers yet.
--
-- The baseline's own header says it is edited in place "pre-deploy". That
-- window closed the day #285 pushed it. From here every schema change is a new
-- migration file; tests/migrations-applied.test.ts holds that line.

